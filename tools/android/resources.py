#!/usr/bin/env python3
"""Generate the Android app's resources that come from the rest of the repository.

- android/app/src/main/res/xml/locales_config.xml: the interface languages (i18n/languages.tsv),
  for Android 13's per-app language setting.
- android/app/src/main/res/mipmap-*/ic_launcher.png: the app icon, from
  crates/app/assets/icons/app/mdm-256.png.

Run after adding a language or changing the icon: python tools/android/resources.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android/app/src/main/res"


def bcp47(code: str) -> str:
    """craft-i18n's lowercase codes as Android's locale tags (zh-hant -> zh-Hant, pt-br -> pt-BR)."""
    parts = code.split("-")
    out = [parts[0]]
    for p in parts[1:]:
        if len(p) == 4:
            out.append(p.title())
        elif len(p) in (2, 3) and p.isalpha():
            out.append(p.upper())
        else:
            out.append(p)
    return "-".join(out)


def locales() -> None:
    codes = []
    for line in (ROOT / "i18n/languages.tsv").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        code = line.split("\t")[0].strip()
        if code and code != "code":
            codes.append(bcp47(code))
    if "en" not in codes:
        codes.insert(0, "en")
    body = "\n".join(f'    <locale android:name="{c}" />' for c in codes)
    (RES / "xml").mkdir(parents=True, exist_ok=True)
    (RES / "xml/locales_config.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/android/resources.py from i18n/languages.tsv. -->\n"
        '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f"{body}\n</locale-config>\n",
        encoding="utf-8",
    )
    print(f"{len(codes)} locales")


def icons() -> None:
    from PIL import Image

    src = Image.open(ROOT / "crates/app/assets/icons/app/mdm-256.png").convert("RGBA")
    for name, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        d = RES / f"mipmap-{name}"
        d.mkdir(parents=True, exist_ok=True)
        src.resize((px, px), Image.LANCZOS).save(d / "ic_launcher.png", optimize=True)
    print("icons")


if __name__ == "__main__":
    locales()
    icons()
