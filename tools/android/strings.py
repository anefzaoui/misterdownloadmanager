#!/usr/bin/env python3
"""The Android app's texts in every interface language, from the catalogs (i18n/*.tsv).

Each string of android/app/src/main/res/values/strings.xml is a catalog row of context "android"
(tools/i18n/extract.py adds them, tools/i18n/translate.py translates them; see texts.py), and
each plural an `@plural` row. This writes every language's translations of them as
values-<language>/strings.xml (generated: never edit those). A string a catalog doesn't
translate yet stays English there, and so does one whose translation lost a placeholder.

    python tools/android/strings.py [--missing]

`--missing` lists, per language, how many of the app's texts its catalog lacks.
Plural forms map to Android's quantities by the language's CLDR categories, as craft-i18n
orders them (needs Babel, as translate.py does).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import texts  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android/app/src/main/res"
NOTE = "<!-- Generated by tools/android/strings.py from i18n/{code}.tsv: edit the catalog, not this file. -->"
RANK = ["zero", "one", "two", "few", "many", "other"]


def qualifier(code: str) -> str:
    """craft-i18n's code as a resource folder's qualifier: pt-br -> pt-rBR, zh-hans -> b+zh+Hans."""
    parts = code.split("-")
    if len(parts) == 1:
        return parts[0]
    if len(parts) == 2 and len(parts[1]) == 2:
        return f"{parts[0]}-r{parts[1].upper()}"
    out = [parts[0]] + [p.title() if len(p) == 4 else p.upper() for p in parts[1:]]
    return "b+" + "+".join(out)


def catalog(path: Path):
    """(rows by (context, source), plural rows by source "one|other")."""
    rows, plurals = {}, {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or "\t" not in line:
            continue
        parts = line.split("\t")
        if len(parts) < 3 or not parts[2]:
            continue
        if parts[0] == "@plural":
            plurals[parts[1]] = parts[2]
        else:
            rows[(parts[0], parts[1])] = parts[2]
    return rows, plurals


def categories(code: str):
    """The language's plural categories whole numbers reach, in craft-i18n's order."""
    try:
        from babel import Locale
    except ImportError:
        return None
    try:
        rule = Locale.parse(code.replace("-", "_")).plural_form
    except Exception:
        return None
    reached = {rule(n) for n in range(1001)}
    return [c for c in RANK if c in reached]


def main() -> None:
    strings = texts.strings()
    plurals = texts.plurals()
    report = []
    written = 0
    for tsv in sorted((ROOT / "i18n").glob("*.tsv")):
        code = tsv.stem
        if code == "en":
            continue
        rows, prows = catalog(tsv)
        out = []
        for key, android, text in strings:
            t = rows.get(("android", text)) or rows.get(("", text))
            back = texts.from_catalog(key, android, t) if t else None
            if back is not None:
                out.append(f'    <string name="{key}">{texts.escape(back)}</string>')
        cats = categories(code)
        for key, one, other in plurals:
            forms = prows.get(f"{one}|{other}")
            if not forms or not cats:
                continue
            forms = forms.split("|")
            if len(forms) != len(cats):
                continue
            items = dict(zip(cats, forms))
            # Android may ask for a category the integers never reach (Russian `other` for
            # 1.5): the `few` form, else the last, as craft-i18n does.
            items.setdefault("other", items.get("few", forms[-1]))
            body = "\n".join(
                f'        <item quantity="{q}">{texts.escape(f.replace("{n}", "%d"))}</item>' for q, f in items.items()
            )
            out.append(f'    <plurals name="{key}">\n{body}\n    </plurals>')
        report.append((code, len(strings) + len(plurals) - len(out)))
        folder = RES / f"values-{qualifier(code)}"
        if not out:
            continue
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "strings.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n' + NOTE.format(code=code) + "\n<resources>\n" + "\n".join(out) + "\n</resources>\n",
            encoding="utf-8",
        )
        written += 1
    total = len(strings) + len(plurals)
    done = sum(total - missing for _, missing in report)
    print(f"{written} languages; {done} of {total * len(report)} texts translated")
    if "--missing" in sys.argv:
        for code, missing in report:
            print(f"{code}\t{missing} missing")


if __name__ == "__main__":
    main()
